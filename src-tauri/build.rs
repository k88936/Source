use std::path::{Path, PathBuf};

/// Commands registered by `generate_handler!` in `src/lib.rs`.
///
/// Tauri only accepts app commands from a non-`devUrl` origin when the app
/// declares an ACL manifest that grants them, and a permission can only list
/// concrete command names. Reading the list off the invoke handler keeps the
/// grant from drifting away from the registered commands.
fn app_commands() -> Vec<String> {
    let source = std::fs::read_to_string("src/lib.rs").expect("cannot read src/lib.rs");
    let start = source
        .find("generate_handler![")
        .expect("src/lib.rs has no generate_handler!");
    let body = &source[start + "generate_handler![".len()..];
    let end = body.find(']').expect("unterminated generate_handler!");

    let mut commands: Vec<String> = body[..end]
        .split(',')
        .filter_map(|entry| entry.trim().rsplit("::").next())
        .filter(|name| !name.is_empty())
        .map(str::to_owned)
        .collect();
    commands.dedup();
    commands
}

/// Writes `<out>/app-commands.toml` granting every app command, returning the
/// glob pattern tauri-build should read permissions from.
fn dev_permissions(out_dir: &Path) -> String {
    let dir = out_dir.join("dev-permissions");
    std::fs::create_dir_all(&dir).expect("cannot create dev-permissions");

    let allow = app_commands()
        .iter()
        .map(|command| format!("\"{command}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let manifest = format!(
        "# Generated by build.rs from generate_handler! in src/lib.rs.\n\
         [[permission]]\n\
         identifier = \"app-commands\"\n\
         description = \"Every command registered by the app.\"\n\
         commands.allow = [{allow}]\n"
    );

    let path = dir.join("app-commands.toml");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(manifest.as_str()) {
        std::fs::write(&path, manifest).expect("cannot write app-commands.toml");
    }

    dir.join("*.toml").display().to_string()
}

fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");

    let debug = std::env::var("DEBUG").as_deref() != Ok("false");
    let attributes = if debug {
        // A dev window follows `tmp/vite.json`, so its origin can be any Vite
        // port; Tauri treats that as remote and requires an explicit grant.
        // `dev.json` therefore carries the remote origin and every permission
        // the app needs, and is the only capability a dev build sees.
        println!("cargo:rerun-if-changed=capabilities/dev.json");
        let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is not set"));
        let pattern: &'static str = Box::leak(dev_permissions(&out_dir).into_boxed_str());
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().permissions_path_pattern(pattern))
            .capabilities_path_pattern("./capabilities/dev.json")
    } else {
        // Release builds load the bundled frontend only, so the capabilities
        // that exist for the dev server are left out entirely.
        tauri_build::Attributes::new().capabilities_path_pattern("./capabilities/default.json")
    };

    tauri_build::try_build(attributes).expect("failed to run tauri-build");
}
